"""Column classes (N/I) read from the DDL comments; renders the format spec's Appendix A.

Run `python -m ad2v.ddl` to regenerate the appendix in docs/spec/ad2v-format-v0.4.md.
"""

from __future__ import annotations

import re
import sqlite3
from pathlib import Path

from ad2v.resources import ddl_path

MARK_RE = re.compile(r"--\s*(N/I|N|I|V)\b\s*(.*)$")
BEGIN = "<!-- BEGIN COLUMN CLASSES (generated by `python -m ad2v.ddl`) -->"
END = "<!-- END COLUMN CLASSES -->"


def column_classes() -> dict[str, list[tuple[str, str, str]]]:
    """{table: [(column, class, note)]} in DDL order. Raises if a column has no mark."""
    ddl = ddl_path().read_text(encoding="utf-8")
    conn = sqlite3.connect(":memory:")
    conn.executescript(ddl)
    tables = [r[0] for r in conn.execute("SELECT name FROM sqlite_master WHERE type='table' ORDER BY rowid")]
    out: dict[str, list[tuple[str, str, str]]] = {}
    for t in tables:
        block = re.search(rf"CREATE TABLE {t} \((.*?)\n\);", ddl, re.S)
        assert block is not None, t
        lines = block.group(1).split("\n")
        rows = []
        for _cid, col, *_rest in conn.execute(f"PRAGMA table_info({t})"):
            line = next(
                (ln for ln in lines if re.search(rf"(^|[\s,]){col}\s+(TEXT|INTEGER|REAL|BLOB)\b", ln)), None
            )
            m = MARK_RE.search(line) if line else None
            if m is None:
                raise ValueError(f"{t}.{col}: no N/I/V mark in DDL")
            rows.append((col, m.group(1), m.group(2).strip()))
        out[t] = rows
    conn.close()
    return out


def render() -> str:
    parts = [BEGIN, ""]
    for table, cols in column_classes().items():
        parts.append(f"**{table}**\n")
        parts.append("| column | class | note |\n|---|---|---|")
        for c, k, n in cols:
            note = n.replace("|", "\\|")
            parts.append(f"| `{c}` | {k} | {note} |")
        parts.append("")
    parts.append(END)
    return "\n".join(parts)


def update_spec(spec: Path) -> bool:
    text = spec.read_text(encoding="utf-8")
    start, end = text.index(BEGIN), text.index(END) + len(END)
    new = text[:start] + render() + text[end:]
    if new != text:
        spec.write_text(new, encoding="utf-8", newline="\n")
        return True
    return False


if __name__ == "__main__":
    root = Path(__file__).resolve().parents[2]
    changed = update_spec(root / "docs" / "spec" / "ad2v-format-v0.4.md")
    print("updated" if changed else "up to date")
